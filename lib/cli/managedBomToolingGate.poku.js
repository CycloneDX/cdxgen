/**
 * Tests that scans with dependency installation disabled never start the
 * project's own build tooling for Python (poetry/pdm export evaluates the
 * project's configuration; Poetry 2 even loads .pth plugins from the project
 * tree) and .NET (`dotnet msbuild` evaluates the project and auto-reads
 * Directory.Build.rsp). The fixtures mirror the marker-file reproducers of
 * issue #4527; stand-ins on PATH record every invocation.
 */
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { delimiter, join } from "node:path";
import process from "node:process";

import { assert, it } from "poku";

import { getLedgerEvents, resetLedgerEvents } from "../core/buildLedger.js";
import { resetRunState } from "../core/runState.js";

const ENV_NAMES = [
  "PATH",
  "HOME",
  "DOTNET_CMD",
  "CDXGEN_INTROSPECT",
  "CDXGEN_INTROSPECT_LEDGER",
  "FETCH_LICENSE",
];

const PYPROJECT = `[tool.poetry]
name = "demo"
version = "1.0.0"
description = "Demo project"
authors = []

[tool.poetry.dependencies]
python = ">=3.9"
requests = "^2.32"

[build-system]
requires = ["poetry-core>=2.0.0"]
build-backend = "poetry.core.masonry.api"
`;

const POETRY_LOCK = `# This file is automatically @generated by Poetry 2.4.1 and should not be changed by hand.
version = "2.4.1"

[[package]]
name = "certifi"
version = "2024.12.14"
description = "Python package for providing Mozilla's CA Bundle."
optional = false
python-versions = ">=3.6"
groups = ["main"]

[[package]]
name = "requests"
version = "2.32.3"
description = "Python HTTP for Humans."
optional = false
python-versions = ">=3.8"
groups = ["main"]

[package.dependencies]
certifi = ">=2017.4.17"

[metadata]
lock-version = "2.1"
content-hash = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
`;

const CSPROJ = `<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
  </PropertyGroup>
  <ItemGroup>
    <PackageReference Include="Serilog" Version="2.12.0" />
    <PackageReference Include="Newtonsoft.Json" Version="$(NewtonsoftVersion)" />
  </ItemGroup>
</Project>
`;

/**
 * Write a stand-in executable that records its invocation into a marker file.
 *
 * @param {string} binDir Directory to place the tool in.
 * @param {string} name Tool file name.
 * @param {string} marker Marker file the tool writes on invocation.
 * @param {string} [extraSh] Extra shell run after the marker write (e.g. to
 *   answer version probes).
 */
function writeFakeTool(binDir, name, marker, extraSh = "") {
  const tool = join(binDir, name);
  writeFileSync(
    tool,
    `#!/bin/sh\nprintf 'ran\\n' > ${JSON.stringify(marker)}\n${extraSh}`,
  );
  chmodSync(tool, 0o755);
}

/**
 * Create the scratch root with a bin directory and a saved environment.
 *
 * @param {string} stem Temp directory stem.
 * @returns {{root: string, binDir: string, saved: Object, printed: string[], hookConsole: Function, restoreConsole: Function, restoreEnv: Function, marker: Function}}
 */
function setupScratch(stem) {
  const root = mkdtempSync(join(tmpdir(), stem));
  const binDir = join(root, "bin");
  const emptyHome = join(root, "home");
  mkdirSync(binDir);
  mkdirSync(emptyHome);
  const saved = Object.fromEntries(ENV_NAMES.map((n) => [n, process.env[n]]));
  const printed = [];
  const originalLog = console.log;
  return {
    root,
    binDir,
    saved,
    printed,
    hookConsole() {
      console.log = (...args) => printed.push(args.join(" "));
    },
    restoreConsole() {
      console.log = originalLog;
    },
    /**
     * Apply the isolated environment (fake tools first on PATH) and enable the
     * in-memory ledger without turning introspection mode on.
     */
    applyEnv() {
      for (const name of ENV_NAMES) {
        delete process.env[name];
      }
      process.env.PATH = [binDir, saved.PATH].filter(Boolean).join(delimiter);
      process.env.HOME = emptyHome;
      process.env.CDXGEN_INTROSPECT_LEDGER = join(root, "ledger.jsonl");
    },
    restoreEnv() {
      for (const [name, value] of Object.entries(saved)) {
        if (value === undefined) {
          delete process.env[name];
        } else {
          process.env[name] = value;
        }
      }
    },
    marker(name) {
      return join(root, name);
    },
  };
}

await it("does not run poetry export with --no-install-deps and keeps the lock file packages", async () => {
  if (process.platform === "win32") {
    // The stand-ins are POSIX shell scripts.
    return;
  }
  const scratch = setupScratch("cdxgen-poetry-gate-");
  const project = join(scratch.root, "project");
  mkdirSync(join(project, ".poetry", "plugins"), { recursive: true });
  writeFileSync(join(project, "pyproject.toml"), PYPROJECT);
  writeFileSync(join(project, "poetry.lock"), POETRY_LOCK);
  // The payload shape of issue #4527: Poetry 2 adds the project's
  // .poetry/plugins directory to sys.path, so a .pth file there runs.
  writeFileSync(
    join(project, ".poetry", "plugins", "x.pth"),
    'import pathlib; pathlib.Path("POETRY_PLUGIN_RAN").write_text("ran")\n',
  );
  writeFakeTool(scratch.binDir, "poetry", scratch.marker("poetry-ran"));
  try {
    scratch.applyEnv();
    scratch.hookConsole();
    resetRunState();
    resetLedgerEvents();
    const { createPythonBom } = await import("./managedBom.js");
    const bomNSData = await createPythonBom(project, {
      deep: true,
      installDeps: false,
      projectType: ["python"],
      specVersion: 1.6,
    });
    assert.strictEqual(
      existsSync(scratch.marker("poetry-ran")),
      false,
      "poetry started even though dependency installation is disabled",
    );
    assert.ok(
      scratch.printed.some((line) =>
        line.includes(
          "Skipping 'poetry/pdm export' since dependency installation is disabled",
        ),
      ),
      `expected a skip message, printed: ${scratch.printed.join(" | ")}`,
    );
    assert.ok(
      getLedgerEvents().some(
        (event) =>
          event.remediationId === "python.poetry-export.tooling-disabled",
      ),
      "expected a python.poetry-export.tooling-disabled degradation event",
    );
    const names = (bomNSData?.bomJson?.components || []).map((c) => c.name);
    assert.ok(names.includes("requests"), `requests missing from ${names}`);
    assert.ok(names.includes("certifi"), `certifi missing from ${names}`);
  } finally {
    scratch.restoreConsole();
    scratch.restoreEnv();
    resetRunState();
    resetLedgerEvents();
    rmSync(scratch.root, { force: true, recursive: true });
  }
});

await it("does not run poetry export for an empty poetry.lock (issue #4527 reproducer)", async () => {
  if (process.platform === "win32") {
    return;
  }
  const scratch = setupScratch("cdxgen-poetry-empty-gate-");
  const project = join(scratch.root, "project");
  mkdirSync(join(project, ".poetry", "plugins"), { recursive: true });
  writeFileSync(join(project, "pyproject.toml"), PYPROJECT);
  // An empty lock is what the issue used: no dependency tree, so the export
  // path is reached even without --deep.
  writeFileSync(join(project, "poetry.lock"), "");
  writeFileSync(
    join(project, ".poetry", "plugins", "x.pth"),
    'import pathlib; pathlib.Path("POETRY_PLUGIN_RAN").write_text("ran")\n',
  );
  writeFakeTool(scratch.binDir, "poetry", scratch.marker("poetry-ran"));
  try {
    scratch.applyEnv();
    scratch.hookConsole();
    resetRunState();
    resetLedgerEvents();
    const { createPythonBom } = await import("./managedBom.js");
    await createPythonBom(project, {
      installDeps: false,
      projectType: ["python"],
      specVersion: 1.6,
    });
    assert.strictEqual(
      existsSync(scratch.marker("poetry-ran")),
      false,
      "poetry started for an empty lock even though dependency installation is disabled",
    );
  } finally {
    scratch.restoreConsole();
    scratch.restoreEnv();
    resetRunState();
    resetLedgerEvents();
    rmSync(scratch.root, { force: true, recursive: true });
  }
});

