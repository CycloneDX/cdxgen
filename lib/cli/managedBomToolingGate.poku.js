await it("does not evaluate msbuild properties with --no-install-deps and keeps static references", async () => {
  if (process.platform === "win32") {
    return;
  }
  const scratch = setupScratch("cdxgen-dotnet-gate-");
  const project = join(scratch.root, "project");
  mkdirSync(project);
  writeFileSync(join(project, "demo.csproj"), CSPROJ);
  // The payload shape of issue #4527: MSBuild auto-reads this response file,
  // and a -t: switch in it runs the target Directory.Build.targets defines.
  writeFileSync(join(project, "Directory.Build.rsp"), "-t:Evil\n");
  writeFileSync(
    join(project, "Directory.Build.targets"),
    '<Project><Target Name="Evil"><Touch Files="$(MSBuildThisFileDirectory)DOTNET_TARGET_RAN" AlwaysCreate="true" /></Target></Project>\n',
  );
  writeFakeTool(scratch.binDir, "dotnet", scratch.marker("dotnet-ran"));
  try {
    scratch.applyEnv();
    scratch.hookConsole();
    resetRunState();
    resetLedgerEvents();
    const { createCsharpBom } = await import("./managedBom.js");
    const bomNSData = await createCsharpBom(project, {
      installDeps: false,
      projectType: ["dotnet"],
      specVersion: 1.6,
    });
    assert.strictEqual(
      existsSync(scratch.marker("dotnet-ran")),
      false,
      "dotnet started even though dependency installation is disabled",
    );
    assert.ok(
      scratch.printed.some((line) =>
        line.includes(
          "Skipping 'dotnet msbuild' property evaluation since dependency installation is disabled",
        ),
      ),
      `expected a skip message, printed: ${scratch.printed.join(" | ")}`,
    );
    assert.ok(
      getLedgerEvents().some(
        (event) => event.remediationId === "dotnet.msbuild.tooling-disabled",
      ),
      "expected a dotnet.msbuild.tooling-disabled degradation event",
    );
    const serilog = (bomNSData?.bomJson?.components || []).find(
      (c) => c.name === "Serilog",
    );
    assert.ok(serilog, "the statically versioned reference is missing");
    assert.strictEqual(serilog.version, "2.12.0");
  } finally {
    scratch.restoreConsole();
    scratch.restoreEnv();
    resetRunState();
    resetLedgerEvents();
    rmSync(scratch.root, { force: true, recursive: true });
  }
});

await it("still evaluates msbuild properties when dependency installation is enabled", async () => {
  if (process.platform === "win32") {
    return;
  }
  const scratch = setupScratch("cdxgen-dotnet-control-");
  const project = join(scratch.root, "project");
  mkdirSync(project);
  writeFileSync(join(project, "demo.csproj"), CSPROJ);
  writeFakeTool(
    scratch.binDir,
    "dotnet",
    scratch.marker("dotnet-ran"),
    `case "$*" in
      *--version*) echo "17.11.4.5f10f87af";;
      *-getProperty*) echo "13.0.3";;
      *) echo "";;
    esac
    exit 0
    `,
  );
  try {
    scratch.applyEnv();
    resetRunState();
    const { createCsharpBom } = await import("./managedBom.js");
    const bomNSData = await createCsharpBom(project, {
      installDeps: true,
      projectType: ["dotnet"],
      specVersion: 1.6,
    });
    assert.strictEqual(
      existsSync(scratch.marker("dotnet-ran")),
      true,
      "the stand-in dotnet was never invoked",
    );
    const newtonsoft = (bomNSData?.bomJson?.components || []).find(
      (c) => c.name === "Newtonsoft.Json",
    );
    assert.ok(
      newtonsoft,
      "the $(NewtonsoftVersion) reference was not resolved by the property evaluation",
    );
    assert.strictEqual(newtonsoft.version, "13.0.3");
  } finally {
    scratch.restoreEnv();
    resetRunState();
    rmSync(scratch.root, { force: true, recursive: true });
  }
});
