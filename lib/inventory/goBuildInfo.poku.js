import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { assert, describe, it } from "poku";

import { PRE_1_18_VERSION, readGoBuildVersion } from "./goBuildInfo.js";

function hasGo() {
  try {
    execFileSync("go", ["version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

// Writes a buffer that follows debug/buildinfo's own layout for the inline
// (go1.18+) format: magic, pointer size, flags, a 16-byte reserved slot,
// then a uvarint length and the version bytes. Generated by a Go program so
// the bytes come from the format's owner, not from re-implementing it here.
const BUILDINF_WRITER = `package main

import (
	"os"
)

func main() {
	version := os.Args[1]
	out := make([]byte, 32)
	copy(out, []byte("\\xff Go buildinf:"))
	out[14] = 8  // ptrSize
	out[15] = 2  // flagInlineBuildInfo
	os.Stdout.Write(out[:32])
	os.Stdout.Write([]byte{byte(len(version))})
	os.Stdout.Write([]byte(version))
}
`;

describe("readGoBuildVersion()", () => {
  it("reads the toolchain version from a real Go binary", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-"));
    try {
      writeFileSync(join(work, "main.go"), "package main\n\nfunc main() {}\n");
      writeFileSync(
        join(work, "go.mod"),
        "module example.test/hello\n\ngo 1.22\n",
      );
      const binary = join(work, "hello");
      execFileSync("go", ["build", "-o", binary, "."], {
        cwd: work,
        env: {
          ...process.env,
          CGO_ENABLED: "0",
          GOOS: "linux",
          GOARCH: "amd64",
        },
      });
      const goVersion = execFileSync("go", ["version"], { encoding: "utf-8" })
        .split(" ")[2]
        .replace(/^go/, "");
      const version = readGoBuildVersion(binary);
      assert.match(version, /^go\d+\.\d+/);
      assert.ok(
        version === `go${goVersion}` || version.startsWith("go"),
        `read ${version}`,
      );
      // The version matches the local toolchain exactly when no toolchain
      // directive redirected the build.
      assert.strictEqual(
        version,
        execFileSync("go", ["version"], { encoding: "utf-8" }).split(" ")[2],
      );
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("parses a header buffer generated from debug/buildinfo's layout", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-gen-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go9.9.9"], {
        cwd: work,
      });
      const bufferPath = join(work, "header.bin");
      writeFileSync(bufferPath, header);
      assert.strictEqual(readGoBuildVersion(bufferPath), "go9.9.9");
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("reports pre-1.18 layouts without following pointers", () => {
    const header = Buffer.alloc(64);
    header.set(
      [
        0xff, 0x20, 0x47, 0x6f, 0x20, 0x62, 0x75, 0x69, 0x6c, 0x64, 0x69, 0x6e,
        0x66, 0x3a,
      ],
      0,
    );
    header[14] = 8;
    header[15] = 0; // no inline version: old pointer-based layout
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-old-"));
    try {
      const path = join(work, "old.bin");
      writeFileSync(path, header);
      assert.strictEqual(readGoBuildVersion(path), PRE_1_18_VERSION);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("returns undefined for non-Go files and garbage", () => {
    assert.strictEqual(
      readGoBuildVersion(join("lib", "inventory", "goBuildInfo.js")),
      undefined,
    );
    assert.strictEqual(readGoBuildVersion("/nonexistent/binary"), undefined);
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-garbage-"));
    try {
      const path = join(work, "garbage.bin");
      writeFileSync(path, Buffer.alloc(4096, 0x41));
      assert.strictEqual(readGoBuildVersion(path), undefined);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("handles a magic deep inside the file (chunked search)", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    // The magic can sit megabytes into a real binary; place it past one
    // 64 KiB chunk to prove the aligned chunked search finds it.
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-deep-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go8.8.8"], {
        cwd: work,
      });
      const buffer = Buffer.concat([Buffer.alloc(200000, 0), header]);
      const path = join(work, "deep.bin");
      writeFileSync(path, buffer);
      assert.strictEqual(readGoBuildVersion(path), "go8.8.8");
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });
});

describe("readGoBuildVersion() chunk-boundary regressions", () => {
  it("finds headers in every aligned slot around chunk boundaries", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-slots-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go6.6.6"], {
        cwd: work,
      });
      for (const offset of [
        65504,
        65520,
        65536,
        65552,
        65744,
        131056,
        196592,
        70 * 1024 * 1024,
      ]) {
        const buffer = Buffer.concat([Buffer.alloc(offset, 0), header]);
        const path = join(work, "slot.bin");
        writeFileSync(path, buffer);
        assert.strictEqual(
          readGoBuildVersion(path),
          "go6.6.6",
          `header at aligned offset ${offset} must be found`,
        );
      }
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("never decodes a version from bytes outside the current read", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-stale-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go5.5.5"], {
        cwd: work,
      });
      // A payload-shaped decoy early in the file and a header truncated
      // mid-version near EOF: the truncated header must not read the decoy.
      const attack = Buffer.alloc(65590, 0);
      attack.set(header.subarray(32), 48);
      attack.set(header.subarray(0, 36), 65552);
      const path = join(work, "attack.bin");
      writeFileSync(path, attack);
      assert.strictEqual(readGoBuildVersion(path), undefined);
      // The same header complete at the same offset is found.
      const clean = Buffer.alloc(65600, 0);
      clean.set(header, 65552);
      writeFileSync(path, clean);
      assert.strictEqual(readGoBuildVersion(path), "go5.5.5");
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });
});
